from __future__ import annotations

from dataclasses import dataclass, fields
from typing import Optional, Union

import numpy as np
import sapien
import torch
from sapien.sensor import StereoDepthSensor, StereoDepthSensorConfig

from mani_skill.utils import common, sapien_utils
from mani_skill.utils.structs import Actor, Articulation, Link

from .base_sensor import BaseSensor
from .camera import Camera, CameraConfig, camera_observations_to_images


@dataclass
class StereoDepthCameraConfig(CameraConfig):
    """Configuration for a simulated active stereo depth camera (e.g. a RealSense D415/D435).

    RGB + depth outputs are generated by simulating a left/right infrared stereo pair
    via :class:`sapien.sensor.StereoDepthSensor`. Note that computing depth with this
    sensor requires CUDA (the stereo matching is executed on the GPU), and the sensor
    is only supported for CPU sim backends with a single environment for now.
    """

    min_depth: float = 0.05
    """minimum valid depth in meters"""
    max_depth: float = 10.0
    """maximum valid depth (non-inclusive) in meters"""
    model: str = "D435"
    """stereo sensor model, one of "D415" or "D435" (see sapien.sensor.StereoDepthSensorConfig)"""

    def __post_init__(self):
        super().__post_init__()
        assert self.model in ("D415", "D435")

    @property
    def rgb_resolution(self):
        return (self.width, self.height)

    @property
    def rgb_intrinsic(self):
        if self.intrinsic is not None:
            return common.to_numpy(self.intrinsic)
        fy = (self.height / 2) / np.tan(self.fov / 2)
        return np.array([[fy, 0, self.width / 2], [0, fy, self.height / 2], [0, 0, 1]])

    @classmethod
    def fromCameraConfig(cls, cfg: CameraConfig):
        field_names = {f.name for f in fields(cls)}
        return cls(**{k: v for k, v in cfg.__dict__.items() if k in field_names})


class StereoDepthCamera(Camera):
    """A stereo depth camera sensor wrapping :class:`sapien.sensor.StereoDepthSensor`.

    It provides the same ``rgb`` and ``depth`` observation modalities as the regular
    :class:`Camera` sensor, but depth is computed by active stereo matching between a
    simulated left/right infrared camera pair instead of being read directly from a
    depth texture.
    """

    config: StereoDepthCameraConfig

    def __init__(
        self,
        camera_config: StereoDepthCameraConfig,
        scene,
        articulation: Optional[Articulation] = None,
    ):
        # note: we bypass Camera.__init__ since this sensor does not use scene.add_camera
        BaseSensor.__init__(self, config=camera_config)

        if scene.gpu_sim_enabled:
            raise NotImplementedError(
                "StereoDepthCamera is currently only supported for the CPU sim backend"
            )
        if len(scene.sub_scenes) != 1:
            raise NotImplementedError(
                "StereoDepthCamera is currently only supported with a single environment (num_envs=1) on the CPU sim backend"
            )

        # resolve the mount entity the same way Camera does
        entity_uid = camera_config.entity_uid
        mount: Optional[Union[Actor, Link]] = camera_config.mount
        if mount is None and entity_uid is not None:
            if articulation is None:
                pass
            else:
                mount = sapien_utils.get_obj_by_name(
                    articulation.get_links(), entity_uid
                )
            if mount is None:
                raise RuntimeError(f"Mount entity ({entity_uid}) is not found")

        sapien_scene = scene.sub_scenes[0]
        if mount is not None:
            if isinstance(mount, Link):
                mount_entity = mount._objs[0].entity
            else:
                mount_entity = mount._objs[0]
        else:
            # no mount given: create a fixed kinematic entity at the camera pose
            mount_entity = sapien.Entity()
            sapien_scene.add_entity(mount_entity)
            mount_entity.pose = camera_config.pose

        sensor_config = StereoDepthSensorConfig(model=camera_config.model)
        sensor_config.rgb_resolution = camera_config.rgb_resolution
        sensor_config.rgb_intrinsic = camera_config.rgb_intrinsic
        sensor_config.ir_resolution = camera_config.rgb_resolution
        sensor_config.ir_intrinsic = camera_config.rgb_intrinsic
        sensor_config.min_depth = camera_config.min_depth
        sensor_config.max_depth = camera_config.max_depth

        self.camera = StereoDepthSensor(sensor_config, mount_entity)
        if mount is None:
            self.camera.set_local_pose(camera_config.pose)

    def capture(self):
        self.camera.take_picture()

    def _compute_depth(self):
        if not torch.cuda.is_available():
            raise RuntimeError(
                "StereoDepthCamera depth computation requires CUDA (the stereo matching runs on the GPU). "
                "Use obs_mode='rgb'/'rgb_dict' or request rgb only if you cannot use a CUDA device."
            )
        self.camera.compute_depth()

    def get_obs(
        self,
        rgb: bool = True,
        depth: bool = True,
        **kwargs,
    ):
        """Returns a dict with the ``rgb`` (H, W, 3) and ``depth`` (H, W, 1) data of this sensor."""
        obs_dict = dict()
        if rgb:
            obs_dict["rgb"] = self.camera.get_rgb()
        if depth:
            self._compute_depth()
            obs_dict["depth"] = self.camera.get_depth()[..., None]
        return obs_dict

    def get_images(self, obs):
        return camera_observations_to_images(obs)

    def get_params(self):
        return dict(
            extrinsic_cv=self.camera._cam_rgb.get_extrinsic_matrix(),
            cam2world_gl=self.camera._cam_rgb.get_model_matrix(),
            intrinsic_cv=self.camera._cam_rgb.get_intrinsic_matrix(),
        )
